/**
 * Refresh `src/openapi/downstream-request-bodies.generated.ts`: the request body
 * schema of each producer route named in `DOWNSTREAM_BODY_SOURCES`, copied out
 * of the producer's SERVED openapi with every `$ref` inlined.
 *
 * Two ways to feed it producer documents:
 *   tsx scripts/sync-downstream-bodies.ts --from docs.json
 *       docs.json = { "<service-name>": <that service's openapi.json>, ... }
 *   tsx scripts/sync-downstream-bodies.ts
 *       fetches `${<SERVICE>_SERVICE_URL}/openapi.json` for each service; run it
 *       where those URLs resolve (inside the api-service container on the box).
 *
 * A producer route that is missing from its document fails the run: the mapping
 * is wrong or the route was withdrawn, and either way the gateway must be fixed,
 * not papered over with a stale body.
 */
import * as fs from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
import { DOWNSTREAM_BODY_SOURCES, type DownstreamBodySnapshot } from "../src/openapi/downstream-bodies.js";

type Json = Record<string, unknown>;

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(root, "src/openapi/downstream-request-bodies.generated.ts");

function envName(service: string): string {
  return `${service.replace(/-service$/, "").replace(/-/g, "_").toUpperCase()}_SERVICE_URL`;
}

async function loadDocs(services: string[]): Promise<Record<string, Json>> {
  const fromIdx = process.argv.indexOf("--from");
  if (fromIdx > 0) return JSON.parse(fs.readFileSync(process.argv[fromIdx + 1], "utf8"));
  const docs: Record<string, Json> = {};
  for (const service of services) {
    const base = process.env[envName(service)];
    if (!base) throw new Error(`${envName(service)} is not set`);
    const res = await fetch(`${base}/openapi.json`);
    if (!res.ok) throw new Error(`${service} openapi.json answered ${res.status}`);
    docs[service] = (await res.json()) as Json;
  }
  return docs;
}

/** Path templates match regardless of how each side names its parameters. */
const shape = (p: string) => p.replace(/\{[^}]+\}/g, "{}");

function inline(doc: Json, node: unknown, seen: string[] = []): unknown {
  if (Array.isArray(node)) return node.map((n) => inline(doc, n, seen));
  if (!node || typeof node !== "object") return node;
  const obj = node as Json;
  if (typeof obj.$ref === "string") {
    const name = obj.$ref.split("/").pop()!;
    if (seen.includes(name)) return { type: "object", description: `(recursive ${name})` };
    const target = ((doc.components as Json)?.schemas as Json)?.[name];
    if (!target) throw new Error(`unresolvable $ref ${obj.$ref}`);
    return inline(doc, target, [...seen, name]);
  }
  const out: Json = {};
  for (const [k, v] of Object.entries(obj)) out[k] = inline(doc, v, seen);
  return out;
}

async function main() {
  const services = [...new Set(Object.values(DOWNSTREAM_BODY_SOURCES).map((s) => s.service))];
  const docs = await loadDocs(services);
  const out: Record<string, DownstreamBodySnapshot> = {};
  const problems: string[] = [];
  for (const [key, src] of Object.entries(DOWNSTREAM_BODY_SOURCES).sort(([a], [b]) => a.localeCompare(b))) {
    const doc = docs[src.service];
    if (!doc || (doc as Json).error) {
      problems.push(`${key}: no openapi document for ${src.service}`);
      continue;
    }
    const paths = (doc.paths ?? {}) as Record<string, Json>;
    const match = Object.entries(paths).find(([p]) => shape(p) === shape(src.path));
    const op = match?.[1]?.[src.method.toLowerCase()] as Json | undefined;
    if (!op) {
      problems.push(`${key}: ${src.service} documents no ${src.method} ${src.path}`);
      continue;
    }
    const schema = (((op.requestBody as Json | undefined)?.content as Json | undefined)?.["application/json"] as Json | undefined)?.schema;
    out[key] = { ...src, schema: schema ? (inline(doc, schema) as Json) : null };
  }
  if (problems.length) {
    console.error(`[api-service] sync-downstream-bodies: ${problems.length} problem(s)\n${problems.join("\n")}`);
    process.exit(1);
  }
  const body =
    "// GENERATED by scripts/sync-downstream-bodies.ts from each producer's served openapi.json.\n" +
    "// Do not edit by hand: change DOWNSTREAM_BODY_SOURCES and re-run the script.\n" +
    'import type { DownstreamBodySnapshot } from "./downstream-bodies.js";\n\n' +
    `export const DOWNSTREAM_REQUEST_BODIES: Record<string, DownstreamBodySnapshot> = ${JSON.stringify(out, null, 2)};\n`;
  fs.writeFileSync(outFile, body);
  console.log(`[api-service] wrote ${Object.keys(out).length} request bodies to ${outFile}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
